function InitialGuess = sampleOutputs(QPTraj, Plan, Constants, Limits)
%% Sample Trajectory on Uniform DtSample Grid
    T_total = QPTraj.T_total;
    dt_target = Limits.DtSample;
    Nc = min(3999, max(1, ceil(T_total / dt_target)));
    Nn = Nc + 1;
    t_vec = linspace(0, T_total, Nn);
    dt = T_total / Nc;

    if ~Limits.HasVehicle
        InitialGuess = struct( ...
            'Time',    t_vec, ...
            'X',       zeros(15, Nn), ...
            'U',       zeros(4, Nc), ...
            'T_total', T_total, ...
            'dt_row',  dt * ones(1, Nc) ...
        );
        return;
    end

    [X_nodes, Wrench, ~] = flatnessInvert(QPTraj, t_vec, Plan.HDGRef, Constants, Limits);
    U_nodes = allocateControls(Wrench, Limits);
    U_ctrl  = U_nodes(:, 1:Nc);

    InitialGuess = struct( ...
        'Time',    t_vec, ...
        'X',       X_nodes, ...
        'U',       U_ctrl, ...
        'T_total', T_total, ...
        'dt_row',  dt * ones(1, Nc) ...
    );
end

function Limits = buildVehicleLimits(Constants)
%% Build Vehicle Limits and Flatness Parameters
    % Fixed planner constants
    ThrustMargin = 0.05;
    GimbalMargin = 0.15;
    MaxGimbalAngle = deg2rad(10);
    MaxGimbalRate = deg2rad(35);
    MaxThrustRate = 1500;
    MaxRollRate = 5;
    MaxTilt = deg2rad(30);
    MinSegTime = 0.25;
    DtSample = 0.05;

    % Default empty / kinematics-only fallback
    if isempty(Constants)
        Limits = struct( ...
            'HasVehicle',     false, ...
            'Vehicle',        0, ...
            'g',              9.80145, ...
            'm_init',         1.169, ...
            'm_dry',          1.169, ...
            'OxMass',         0, ...
            'FuMass',         0, ...
            'MaxThrust',      16, ...
            'MaxMdot',        0, ...
            'OF',             1, ...
            'rTB',            0.26, ...
            'CGz_init',       0.26, ...
            'J_init',         diag([0.067, 0.067, 0.02]), ...
            'Rho',            0.067 / (1.169 * 0.26), ...
            'T_lo',           (0.25 + ThrustMargin) * 16, ...
            'T_hi',           (1.00 - ThrustMargin) * 16, ...
            'GimbalLimit',    (1.00 - GimbalMargin) * MaxGimbalAngle, ...
            'GimbalRateLim',  MaxGimbalRate, ...
            'ThrustRateLim',  MaxThrustRate, ...
            'RollLimit',      (1.00 - ThrustMargin) * MaxRollRate, ...
            'RollRateLim',    MaxRollRate, ...
            'MaxTilt',        MaxTilt, ...
            'DefaultMaxAccel',[2.0; 2.0; 3.5], ...
            'MinSegTime',     MinSegTime, ...
            'DtSample',       DtSample ...
        );
        return;
    end

    % Vehicle selection
    veh = Constants.Vehicle;
    MT = Constants.MaxThrust;
    if veh == 1
        minThrottle = 0.50;
        m_lox0 = Constants.OxMass;
        m_ipa0 = Constants.FuMass;
        defAccel = [2.0; 2.0; 3.0];
    else
        minThrottle = 0.25;
        m_lox0 = 0;
        m_ipa0 = 0;
        defAccel = [2.5; 2.5; 3.5];
    end

    % Initial mass, inertia, and center of percussion offset
    m_init = Constants.m_dry + m_lox0 + m_ipa0;
    [J_init, CGz_init] = ComputeJtot(m_lox0, m_ipa0, Constants);
    rho = J_init(1, 1) / (m_init * CGz_init);

    % Effective actuator bands with controller margins
    T_lo = (minThrottle + ThrustMargin) * MT;
    T_hi = (1.00 - ThrustMargin) * MT;
    gimbalLim = (1.00 - GimbalMargin) * MaxGimbalAngle;
    rollLim = (1.00 - ThrustMargin) * MaxRollRate;

    Limits = struct( ...
        'HasVehicle',     true, ...
        'Vehicle',        veh, ...
        'g',              Constants.g, ...
        'm_init',         m_init, ...
        'm_dry',          Constants.m_dry, ...
        'OxMass',         m_lox0, ...
        'FuMass',         m_ipa0, ...
        'MaxThrust',      MT, ...
        'MaxMdot',        Constants.MaxMdot, ...
        'OF',             Constants.OF, ...
        'rTB',            Constants.rTB, ...
        'CGz_init',       CGz_init, ...
        'J_init',         J_init, ...
        'Rho',            rho, ...
        'T_lo',           T_lo, ...
        'T_hi',           T_hi, ...
        'GimbalLimit',    gimbalLim, ...
        'GimbalRateLim',  MaxGimbalRate, ...
        'ThrustRateLim',  MaxThrustRate, ...
        'RollLimit',      rollLim, ...
        'RollRateLim',    MaxRollRate, ...
        'MaxTilt',        MaxTilt, ...
        'DefaultMaxAccel',defAccel, ...
        'MinSegTime',     MinSegTime, ...
        'DtSample',       DtSample ...
    );
end

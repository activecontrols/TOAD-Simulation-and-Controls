% build_mex.m  (run from inside the cpp folder)

eigenDir = 'Extras/eigen-3.4.0/eigen-3.4.0';

% Fail early if a path is wrong
assert(isfile('astra_mex.cpp'),                  'astra_mex.cpp not found. cd into the cpp folder first.');
assert(isfile('Extras/ArduinoEigenDense.h'),     'Extras/ArduinoEigenDense.h not found.');
assert(isfile([eigenDir '/Eigen/Dense']),        'Eigen/Dense not found under %s. Check the doubled folder.', eigenDir);

mex('-D_USE_MATH_DEFINES', ...
    '-IExtras', ...
    ['-I' eigenDir], ...
    '-I.', ...
    'astra_mex.cpp', ...
    'controller_and_estimator.cpp', ...
    'matlab_helpers.cpp', ...
    'GroundEstimator.cpp', ...
    'FlightEstimator.cpp', ...
    'DigitalNF.cpp', ...
    'Q_gen.cpp', ...
    'ASTRAv2_Controller.cpp', ...
    'LESO_Position.cpp', ...
    'LESO_Attitude.cpp');

disp('Build finished.');
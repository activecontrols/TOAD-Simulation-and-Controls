function QT = syntheticQT(t0, E, g, jy, jz, sy, sz, rho)
    Coef = zeros(10, 40, 3);
    % x: E t^2 / 2
    Coef(3, 1, 1) = E / 2;
    % y: jy (t - t0)^3 / 6 + sy (t - t0)^4 / 24, expanded in powers of t
    Coef(1:5, 1, 2) = jy / 6 * [-t0^3; 3 * t0^2; -3 * t0; 1; 0] + sy / 24 * [t0^4; -4 * t0^3; 6 * t0^2; -4 * t0; 1];
    % z: -g t^2 / 2 + jz (t - t0)^3 / 6 + sz (t - t0)^4 / 24
    Coef(1:5, 1, 3) = jz / 6 * [-t0^3; 3 * t0^2; -3 * t0; 1; 0] + sz / 24 * [t0^4; -4 * t0^3; 6 * t0^2; -4 * t0; 1];
    Coef(3, 1, 3) = Coef(3, 1, 3) - g / 2;
    KeyTimes = zeros(1, 41); KeyTimes(2) = 1;
    T = zeros(1, 40); T(1) = 1;
    QT = struct('R', 5, 'Count', 1, 'T', T, 'KeyTimes', KeyTimes, 'Coef', Coef, 'IsHold', false(1, 40), 'IsCruise', false(1, 40), ...
        'Fix', nan(3, 6, 41), 'Cost', 0, 'T_total', 1, 'FlatOffset', rho);
end

function R = fallbackFrame(t, t0, E, g, jy, jz, sy, sz)
    tau = t - t0;
    acc = [E; jy * tau + sy * tau^2 / 2; -g + jz * tau + sz * tau^2 / 2];
    e = acc + [0; 0; g];
    u = e / norm(e);
    cc = cross(u, [0; 1; 0]);
    b2 = cc / norm(cc);
    b1 = cross(b2, u);
    R = [b1, b2, u];
end

function w = fdW(t, t0, E, g, jy, jz, sy, sz, h)
    R0 = fallbackFrame(t, t0, E, g, jy, jz, sy, sz);
    Rd = (fallbackFrame(t + h, t0, E, g, jy, jz, sy, sz) - fallbackFrame(t - h, t0, E, g, jy, jz, sy, sz)) / (2 * h);
    S = R0.' * Rd;
    w = [S(3, 2) - S(2, 3); S(1, 3) - S(3, 1); S(2, 1) - S(1, 2)] / 2;
end

function [w, wd] = fdRates(t0, E, g, jy, jz, sy, sz)
    w = fdW(t0, t0, E, g, jy, jz, sy, sz, 1e-5);
    H = 1e-3;
    wd = (fdW(t0 + H, t0, E, g, jy, jz, sy, sz, 1e-5) - fdW(t0 - H, t0, E, g, jy, jz, sy, sz, 1e-5)) / (2 * H);
end


function [att, tdir, tstep] = stepAtAbort(IG, X_est, c)
    m0 = c.m_dry + X_est(14) + X_est(15);
    T_hover = m0 * c.g;
    q = X_est(1:4) / norm(X_est(1:4));
    b3_est = quatRot(q)' * [0; 0; 1];
    u1 = IG.U(:, 1);
    tB = [cos(u1(1)) * sin(u1(2)); -sin(u1(1)); cos(u1(1)) * cos(u1(2))];
    tI = quatRot(IG.X(1:4, 1))' * tB;
    tdir = rad2deg(acos(max(-1, min(1, dot(tI, b3_est)))));
    b3_plan = quatRot(IG.X(1:4, 1))' * [0; 0; 1];
    att = rad2deg(acos(max(-1, min(1, dot(b3_plan, b3_est)))));
    tstep = (u1(3) - T_hover) / T_hover;
end

function X = tiltedStates(v, n, ctx)
% Tilt <= 30 deg about a random horizontal axis, random heading, |w_B| <= 1 rad/s; position/velocity as the verification box (fixed seed per vehicle).
    rs = RandStream('mt19937ar', 'Seed', 300 + v);
    c = ctx.C{v};
    X = cell(1, n);
    for i = 1:n
        tilt = deg2rad(30) * rand(rs);
        az = 2 * pi * rand(rs);
        psi = 2 * pi * rand(rs) - pi;
        ax = [cos(az); sin(az); 0];
        K = [0, -ax(3), ax(2); ax(3), 0, -ax(1); -ax(2), ax(1), 0];
        Rt = eye(3) + sin(tilt) * K + (1 - cos(tilt)) * (K * K);
        Rz = [cos(psi), -sin(psi), 0; sin(psi), cos(psi), 0; 0, 0, 1];
        q = DCM_Quat_Conversion(Rz * Rt);
        w = randn(rs, 3, 1);
        w = w / norm(w) * rand(rs);
        X{i} = [q; -20 + 40 * rand(rs); -20 + 40 * rand(rs); 0.5 + 39.5 * rand(rs); -5 + 10 * rand(rs); -5 + 10 * rand(rs); -6 + 10 * rand(rs); w; c.OxMass; c.FuMass];
    end
end


function [b3, b3d] = attitudeOf(X_est)
    q = X_est(1:4) / norm(X_est(1:4));
    C_IB = quatRot(q)';
    b3 = C_IB * [0; 0; 1];
    b3d = cross(C_IB * X_est(11:13), b3);
end


function c = abortLegCond(P0, SegT, ctx)
    r = 5;
    K = P0.KnotCount;
    FixP = P0.FixCg(:, 1:r, 1:K);
    % (fixed values do not affect R_PP_eq, so the P-space offset is not applied)
    m1 = P0.LegStartSeg(1);
    m2 = P0.LegEndSeg(P0.LegCount);
    Req = rppEqAsSolved(FixP(:, :, m1:(m2 + 1)), SegT(m1:m2), ctx.H0{r});
    c = 10 ^ maxLogCond(Req);
end

function lc = maxLogCond(Req)
    lc = NaN;
    for d = 1:numel(Req)
        if ~isempty(Req{d})
            lc = max(lc, log10(cond(Req{d})));
        end
    end
end

function e = relErr3(C1, D1, J1, C2, D2, J2)
    e = max([relErr(C1, C2), relErr(D1, D2), relErr(J1, J2)]);
end

function e = relErr(a, b)
    if ~isequal(size(a), size(b))
        e = Inf;
        return;
    end
    a = double(a); b = double(b);
    e = max(abs(a(:) - b(:))) / max(max(abs(b(:))), 1e-300);
end


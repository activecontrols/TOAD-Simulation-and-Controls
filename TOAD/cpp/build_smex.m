% build_smex.m
% Compile the ASTRAv2_SMEX Level-2 C++ Simulink S-Function

thisDir   = fileparts(mfilename('fullpath'));
if isempty(thisDir), thisDir = pwd; end

eigenDir  = fullfile(thisDir, 'Extras', 'eigen-3.4.0', 'eigen-3.4.0');
extrasDir = fullfile(thisDir, 'Extras');

assert(isfile(fullfile(thisDir, 'ASTRAv2_SMEX.cpp')), 'ASTRAv2_SMEX.cpp not found.');
assert(isfile(fullfile(extrasDir, 'ArduinoEigenDense.h')), 'Extras/ArduinoEigenDense.h not found.');
assert(isfile(fullfile(eigenDir, 'Eigen', 'Dense')), 'Eigen/Dense not found.');

mex('-D_USE_MATH_DEFINES', ...
    ['-I' extrasDir], ...
    ['-I' eigenDir], ...
    ['-I' thisDir], ...
    fullfile(thisDir, 'ASTRAv2_SMEX.cpp'), ...
    fullfile(thisDir, 'controller_and_estimator.cpp'), ...
    fullfile(thisDir, 'matlab_helpers.cpp'), ...
    fullfile(thisDir, 'GroundEstimator.cpp'), ...
    fullfile(thisDir, 'FlightEstimator.cpp'), ...
    fullfile(thisDir, 'FlightEstimator2.cpp'), ...
    fullfile(thisDir, 'DigitalNF.cpp'), ...
    fullfile(thisDir, 'Q_gen.cpp'), ...
    fullfile(thisDir, 'ASTRAv2_Controller.cpp'), ...
    fullfile(thisDir, 'LESO_Position.cpp'), ...
    fullfile(thisDir, 'LESO_Attitude.cpp'), ...
    '-outdir', thisDir);

disp('ASTRAv2_SMEX S-Function build finished successfully.');

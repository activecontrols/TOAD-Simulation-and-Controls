%% Parallel Monte Carlo Trajectory Setup & Extraction (V5)
% V5 additions (vehicle-agnostic; only the Actuator Models block needs to change (hopefully):
%   - Per-run seeds for every disturbance AND for the model's noise blocks
%   - Symmetric inertia dispersion (V4 only tested a heavier vehicle)
%   - Physical mean wind in m/s (speed + direction) with Dryden turbulence
%     intensity tied to it
%   - IMU constant biases (accel m/s^2, gyro rad/s), dispersed per run
%   - Magnetometer soft iron (magDistMatrix) and hard iron (magHardIron)
%   - Gimbal / thrust bias through the existing Gimbal Biases path
%   - Time-varying IMU bias hook (IMUBiasDrift, dummy until implemented)
%   - Pass/fail per run (position and attitude error after pad hold)


%% Configuration
model_name = 'TOAD_Simulation';
num_sims = 5;
% Set to true for a new random batch every run, or false to lock a specific seed
use_random_master_seed = true; 

if use_random_master_seed
    rng('shuffle', 'twister');
    rng_state = rng; % rng(...) returns the PREVIOUS state, so query after shuffling
    seed = rng_state.Seed; % Captures the new uint32 seed generated by 'shuffle'
else
    seed = uint32(1788146097); % Paste  previous master seed here to reproduce and set use_random_master_seed to false
    rng(seed, 'twister');
end

% Fast Restart skips recompiling between runs. If parsim reports that a
% non-tunable parameter changed (e.g. a noise-seed field), set this false.
use_fast_restart = true;

clear simIn out

%% Nominal parameters
% Vehicle constants struct (swap for the other vehicle's struct when flying
% ASTRA vs TOAD)
vehicle_constants = constantsTOAD;

GrommetIDX = 2;
J_nom = vehicle_constants.J;
G = GrommetSelect(GrommetIDX);
m_FC = 0.1;
K_nom = G.K;
B_nom = G.C / (2 * sqrt(K_nom * m_FC));

%% V5 disturbance settings (all dispersion sizes in one place)
% Inertia: symmetric +/- fraction of nominal per principal axis
J_frac = 0.10;

% Mean wind, at the 6 m reference height used by the Dryden block
wind_sweep        = false;   % true: uniform 0..wind_max (envelope search)
wind_max          = 12;      % m/s, upper end of the envelope sweep
wind_weibull_scale = 4.0;    % m/s, operational campaign (TODO: fit to site data)
wind_weibull_shape = 2.0;    % Rayleigh-like; matches measured surface wind
dryden_W6         = 15;      % m/s, "Wind speed at 6 m" set in the Dryden block mask
turb_mult_range   = [0.5, 2.0]; % multiplier on spec turbulence intensity

% IMU constant biases, perturbed around the LoadTOADSim values
accelBias_nom   = accelBias;              % m/s^2
gyroBias_nom    = gyroBias;               % rad/s
sigma_accelBias = 0.02;                   % m/s^2 (~2 mg) 1-sigma per axis
sigma_gyroBias  = deg2rad(0.1);           % rad/s 1-sigma per axis

% Magnetometer, perturbed around the LoadTOADSim values
magDist_nom     = magDistMatrix;
if exist('magHardIron', 'var')
    magHardIron_nom = magHardIron;
else
    magHardIron_nom = 0.05 * ones(3,1);   % value currently hard-coded in Rotate1
end
sigma_softIron  = 0.01;                   % per element of the (symmetric) matrix
sigma_hardIron  = 0.02;                   % fraction of |B| per axis

% Gimbal / thrust bias, entering at U_SIM = [theta; phi; thrust; roll]
sigma_gimbalBias = deg2rad(0.25);         % rad per gimbal axis
sigma_thrustBias = 0.02;                  % fraction of hover thrust
hover_thrust     = vehicle_constants.m_wet * vehicle_constants.g;

% Time-varying IMU bias (Brownian motion with Drift) parameters for IMUBiasDrift
% [accel_sigma (m/s^2), accel_tau (s), gyro_sigma (rad/s), gyro_tau (s), seed]
accelDrift_sigma_range = [0.005, 0.02];
gyroDrift_sigma_range  = deg2rad([0.005, 0.02]);
drift_tau_range        = [50, 500];

% Pass/fail thresholds (after the pad hold)
pad_hold_time   = 15;      % s, PadHoldTime in TrajectoryManager
pos_err_fail    = 2.0;     % m, matches max_x_trans position limit
att_err_fail    = 15;      % deg

%% Preallocate Monte Carlo disturbance arrays
J_d_vals  = cell(1, num_sims);
TB_d_vals = cell(1, num_sims);

Wind_Gain_vals  = cell(1, num_sims);
Wind_Covar_vals = cell(1, num_sims);

% V5 disturbance arrays
Wind_Mean_vals      = cell(1, num_sims);   % m/s
Wind_Dir_vals       = cell(1, num_sims);   % rad
windMerid_vals      = cell(1, num_sims);
windZonal_vals      = cell(1, num_sims);
accelBias_vals      = cell(1, num_sims);
gyroBias_vals       = cell(1, num_sims);
magDistMatrix_vals  = cell(1, num_sims);
magHardIron_vals    = cell(1, num_sims);
gimbalBias_vals     = cell(1, num_sims);
IMUDriftParams_vals = cell(1, num_sims);
seedDryden_vals     = cell(1, num_sims);
seedAccel_vals      = cell(1, num_sims);
seedGyro_vals       = cell(1, num_sims);
seedMagNoise_vals   = cell(1, num_sims);

% Store seeds so each trial has different seeds for randomness, but is still
% reproducible 
% Cols: [J seed, TB seed, Wind_Gain seed, Wind_Covar seed,
%        5 mean wind, 6 wind direction, 7 accel bias, 8 gyro bias,
%        9 mag soft iron, 10 mag hard iron, 11 gimbal bias, 12 IMU drift,
%        13 Dryden noise seeds, 14 accel noise seeds, 15 gyro noise seeds,
%        16 mag noise seeds]
% New columns are only ever appended, so existing columns keep their seeds.
num_seed_cols = 16;
rng(double(seed), 'twister');
noiseSeeds = randi(double(intmax('uint32')) - 1, num_sims, num_seed_cols, 'uint32');


%% Legacy / optional uncertainty arrays
% Leave these commented for data-transfer efficiency. Uncomment the
% corresponding generation and setVariable calls if needed.
%
% GyroNoisePower_vals = cell(1, num_sims);
% G_RMAX_vals         = cell(1, num_sims);
% kGrom_vals          = cell(1, num_sims);
% bGrom_vals          = cell(1, num_sims);
% Kg2_vals            = cell(1, num_sims);
% PSD_Low_vals        = cell(1, num_sims);
% PSD_High_vals       = cell(1, num_sims);
%
% % Optional explicit CoM disturbance, if the model exposes a separate
% % CoM_d workspace variable. Keep disabled unless that variable exists.
% % CoM_d_vals = cell(1, num_sims);

%% Preallocate arrays for simulation outputs
RMSE_Controls_all = zeros(12, num_sims);
RMSE_Filter_all   = zeros(3, num_sims);
RMSE_Wind_all     = zeros(1, num_sims);
MaxSpectralRad_all = zeros(2, num_sims);

%% Preallocate interpolated state histories
t_sim = 60;
t_common = (0:0.1:t_sim)';

pos_all  = nan(num_sims, length(t_common), 3);
vel_all  = nan(num_sims, length(t_common), 3);
quat_all = nan(num_sims, length(t_common), 4);
specrad_all = nan(num_sims, length(t_common), 2);
LESODist_all   = nan(num_sims, length(t_common), 6);

% The target is now a full-state trajectory. Its width is determined after
% parsim from the actual target logger rather than assuming a legacy
% waypoint/position-only target format.
target_state_all = [];
disp(seed)
disp(['Generating focused disturbances for ', num2str(num_sims), ' runs with seed ', seed]);

fprintf('Master Seed: %u\n', seed);
fprintf('Generating focused disturbances for %d runs with master seed %u...\n', num_sims, seed);



%% Generate Monte Carlo disturbances
for i = 1:num_sims

    %% 1. Moment of Inertia Disturbances
    rng(double(noiseSeeds(i, 1)), 'twister');
    % V4 (one-sided, heavier only):
    % dI_xx = (0.1 * J_nom(1,1)) * rand();
    % dI_yy = (0.1 * J_nom(2,2)) * rand();
    % dI_zz = (0.1 * J_nom(3,3)) * rand();
    
    % V5: symmetric, so a lighter-than-modeled vehicle is also tested
    dI_xx = (J_frac * J_nom(1,1)) * (2 * rand() - 1);
    dI_yy = (J_frac * J_nom(2,2)) * (2 * rand() - 1);
    dI_zz = (J_frac * J_nom(3,3)) * (2 * rand() - 1);

    % Keep products diagonal to match the V3 disturbance model.
    dI_xy = 0;
    dI_xz = 0;
    dI_yz = 0;

    J_d_vals{i} = [dI_xx, dI_xy, dI_xz;
                   dI_xy, dI_yy, dI_yz;
                   dI_xz, dI_yz, dI_zz];

    %% 2. Center-of-Mass / Lever-Arm Disturbance
    % V3 used TB_d as the 3-axis lever-arm / off-center-CG disturbance.
    % Preserve that model-facing variable and keep its radial/axial
    % components available for sensitivity analysis.
    rng(double(noiseSeeds(i, 2)), 'twister');
    sigma_lever = [0.01; 0.01; 0.01];
    TB_d_vals{i} = randn(3, 1) .* sigma_lever;

    %% 3. Wind Disturbances
    % V3 wind gain distribution and covariance range are retained.
    % V5: the V3 gain draw is replaced by a physical mean wind in m/s, and
    % Wind_Gain now scales the Dryden block (set to dryden_W6) so its
    % intensity matches that mean wind. Wind_Covar is unchanged.

    % 3a. Mean wind speed (m/s) and direction (uniform over 360 deg)
    rng(double(noiseSeeds(i, 5)), 'twister');
    if wind_sweep
        Wind_Mean_vals{i} = wind_max * rand();
    else
        Wind_Mean_vals{i} = wind_weibull_scale * (-log(rand())).^(1/wind_weibull_shape);
    end
    rng(double(noiseSeeds(i, 6)), 'twister');
    Wind_Dir_vals{i} = 2 * pi * rand();
    windMerid_vals{i} = Wind_Mean_vals{i} * cos(Wind_Dir_vals{i});
    windZonal_vals{i} = Wind_Mean_vals{i} * sin(Wind_Dir_vals{i});

    % 3b. Turbulence: low-altitude Dryden intensity is linear in the 6 m
    % wind speed, so scaling its output by U/dryden_W6 gives Dryden at U.
    rng(double(noiseSeeds(i, 3)), 'twister');

    % a = 0.35;
    % b = 2;
    % Wind_Gain_vals{i} = a * (-log(rand(1,1))).^(1/b);

    turb_mult = turb_mult_range(1) + diff(turb_mult_range) * rand();
    Wind_Gain_vals{i} = turb_mult * Wind_Mean_vals{i} / dryden_W6;

    Wind_Speed = hypot(windMerid, windZonal);
    Wind_Dir = atan2(windMerid, windZonal);

    rng(double(noiseSeeds(i, 4)), 'twister');
    Wind_Covar_vals{i} = 8 * rand();

    %% 4. IMU constant biases (per run, around the LoadTOADSim values)
    rng(double(noiseSeeds(i, 7)), 'twister');
    accelBias_vals{i} = accelBias_nom(:) + sigma_accelBias * randn(3, 1);
    rng(double(noiseSeeds(i, 8)), 'twister');
    gyroBias_vals{i}  = gyroBias_nom(:)  + sigma_gyroBias  * randn(3, 1);

    %% 5. Magnetometer soft iron (symmetric) and hard iron
    rng(double(noiseSeeds(i, 9)), 'twister');
    E = sigma_softIron * randn(3);
    magDistMatrix_vals{i} = magDist_nom + (E + E') / 2;
    rng(double(noiseSeeds(i, 10)), 'twister');
    magHardIron_vals{i} = magHardIron_nom(:) + sigma_hardIron * randn(3, 1);

    %% 6. Gimbal / thrust bias  [theta; phi; thrust; roll]
    rng(double(noiseSeeds(i, 11)), 'twister');
    gimbalBias_vals{i} = [sigma_gimbalBias * randn(2, 1);
                          sigma_thrustBias * hover_thrust * randn();
                          0];

    %% 7. Time-varying IMU bias parameters
    rng(double(noiseSeeds(i, 12)), "twister");
    IMUDriftParams_vals{i} = [...
        sigma_accel_mu * rand(1,3), ...
        accel_sigma_range(1) + diff(accel_sigma_range) * rand(), ...
        sigma_gyro_mu * rand(1,3), ...
        gyro_sigma_range(1) + diff(gyro_sigma_range) * rand(), ...
        double(randi(2^31 - 2))];

    %% 8. Noise-block seeds inside the model (so noise differs per run)
    rng(double(noiseSeeds(i, 13)), 'twister');
    seedDryden_vals{i}   = randi(2^31 - 2, 1, 4);
    rng(double(noiseSeeds(i, 14)), 'twister');
    seedAccel_vals{i}    = randi(2^31 - 2, 1, 3);
    rng(double(noiseSeeds(i, 15)), 'twister');
    seedGyro_vals{i}     = randi(2^31 - 2, 1, 3);
    rng(double(noiseSeeds(i, 16)), 'twister');
    seedMagNoise_vals{i} = randi(2^31 - 2, 1, 3);
end

%% Setup Simulation Inputs for Parallel Execution
disp('Configuring Parallel Simulation Inputs...');
simIn(1:num_sims) = Simulink.SimulationInput(model_name);

for i = 1:num_sims
    simIn(i) = simIn(i).setVariable('J_d', J_d_vals{i});
    simIn(i) = simIn(i).setVariable('TB_d', TB_d_vals{i});
    simIn(i) = simIn(i).setVariable('Wind_Gain', Wind_Gain_vals{i});
    simIn(i) = simIn(i).setVariable('Wind_Covar', Wind_Covar_vals{i});

    %% V5 disturbances
    simIn(i) = simIn(i).setVariable('windMerid', windMerid_vals{i});
    simIn(i) = simIn(i).setVariable('windZonal', windZonal_vals{i});
    simIn(i) = simIn(i).setVariable('magDistMatrix', magDistMatrix_vals{i});
    simIn(i) = simIn(i).setVariable('magHardIron', magHardIron_vals{i});
    simIn(i) = simIn(i).setVariable('gimbalBias', gimbalBias_vals{i});
    simIn(i) = simIn(i).setVariable('distMode', 1);   % passes gimbalBias through the Gain block
    simIn(i) = simIn(i).setVariable('IMUDriftParams', IMUDriftParams_vals{i});
    simIn(i) = simIn(i).setVariable('seedDryden', seedDryden_vals{i});
    simIn(i) = simIn(i).setVariable('seedAccel', seedAccel_vals{i});
    simIn(i) = simIn(i).setVariable('seedGyro', seedGyro_vals{i});
    simIn(i) = simIn(i).setVariable('seedMagNoise', seedMagNoise_vals{i});

    %% Optional legacy variables (disabled)
    % simIn(i) = simIn(i).setVariable('gyroNoisePower', GyroNoisePower_vals{i});
    % simIn(i) = simIn(i).setVariable('G_RMAX', G_RMAX_vals{i});
    % simIn(i) = simIn(i).setVariable('kGrom', kGrom_vals{i});
    % simIn(i) = simIn(i).setVariable('bGrom', bGrom_vals{i});
    % simIn(i) = simIn(i).setVariable('Kg2', Kg2_vals{i});
    % simIn(i) = simIn(i).setVariable('lowEnd', PSD_Low_vals{i});
    % simIn(i) = simIn(i).setVariable('highEnd', PSD_High_vals{i});
    %
    % % Explicit CoM disturbance, if supported:
    % simIn(i) = simIn(i).setVariable('CoM_d', CoM_d_vals{i});

    %% Logging: retain only the state and full target trajectory
    % V5: state and target logged at 0.1 s (was 0.5 s) so the pass/fail
    % maxima are not missed between samples.
    
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/state_log'], 'Commented', 'off');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/state_log'], 'SampleTime', '0.1');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/Controller & LESOs/LESODist'], 'Commented', 'off');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/Controller & LESOs/LESODist'], 'SampleTime', '0.1');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/target_pos_log'], 'Commented', 'off');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/target_pos_log'], 'SampleTime', '0.1');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/Controller & LESOs/SpecRad_log'], 'Commented', 'off');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/Controller & LESOs/SpecRad_log'], 'SampleTime', '0.1');

    % Disable unused logs to reduce data movement / RAM use.
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/meas_log'], 'Commented', 'on');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/State Estimator & Filters/Multiplicative Extended Kalman Filter [M-EKF]/MEKF_state'], ...
        'Commented', 'on');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/State Estimator & Filters/Multiplicative Extended Kalman Filter [M-EKF]/MEKF_P'], ...
        'Commented', 'on');
    simIn(i) = simIn(i).setBlockParameter( ...
        [model_name '/inputCMD'], 'Commented', 'on');
end

%% Execute Parallel Simulations
disp('Starting Parallel Monte Carlo Trajectory Simulations (parsim)...');
for i = 1:num_sims
    simIn(i) = simIn(i).setVariable('IMU_Rate', IMU_Rate);
    simIn(i) = simIn(i).setVariable('accelBias', accelBias_vals{i});   % V5: per run
    simIn(i) = simIn(i).setVariable('gyroBias', gyroBias_vals{i});     % V5: per run
    simIn(i) = simIn(i).setVariable('gyroNoisePower', gyroNoisePower);
    simIn(i) = simIn(i).setVariable('dt_SIM', dt_SIM);
    simIn(i) = simIn(i).setVariable('dt', dt);
end

if use_fast_restart, fast_restart = 'on'; else, fast_restart = 'off'; end
out = parsim(simIn, ...
    'ShowProgress', 'on', ...
    'UseFastRestart', fast_restart, ...
    'TransferBaseWorkspaceVariables', 'on');

ok = arrayfun(@(s) isempty(s.ErrorMessage), out);

if ~any(ok)
    error('MonteCarlo:AllRunsFailed', ...
        'No simulations succeeded. First error:\n%s', ...
        out(1).ErrorMessage);
end

%% Extract Metrics and Interpolate Trajectories
disp('Simulations complete. Extracting and interpolating trajectories...');

for i = 1:num_sims
    if isempty(out(i).ErrorMessage)
        % Existing scalar/vector SSE metrics converted to RMSE in the same
        % manner as V3. Wind is now an RMSE metric rather than max-gust.
        RMSE_Controls_all(:, i) = sqrt(out(i).SSE_Controls(:) ./ t_sim);
        RMSE_Filter_all(:, i)   = sqrt(out(i).SSE_Filter(:) ./ t_sim);

        % SSE_Wind is treated as an integrated squared-error metric, just
        % like the other SSE outputs. If it contains multiple wind
        % channels, combine them into one RMS wind-error magnitude.
        wind_sse = out(i).SSE_Wind(:);
        RMSE_Wind_all(i) = sqrt(sum(wind_sse) / t_sim);
        MaxSpectralRad_all(:, i) = out(i).MaxSpectralRad.Data(:);

        % Actual state
        ts_state = out(i).state_log;
        t_raw = ts_state.Time;
        data_raw = squeeze(ts_state.Data);

        if size(data_raw, 1) ~= length(t_raw)
            data_raw = data_raw';
        end

        if size(data_raw,2) < 10
            error('Simulation %d: state_log contains only %d columns; at least 10 are required.', ...
                i, size(data_raw,2));
        end

        quat_raw = data_raw(:, 1:4);
        pos_raw  = data_raw(:, 5:7);
        vel_raw  = data_raw(:, 8:10);

        ts_specrad = out(i).SpecRad_log;
        t_sr = ts_specrad.Time;
        sr_raw = squeeze(ts_specrad.Data);
        if size(sr_raw,1) ~= length(t_sr), sr_raw = sr_raw'; end
        for dim = 1:2
            specrad_all(i,:,dim) = interp1(t_sr, sr_raw(:,dim), ...
                t_common, 'linear', 'extrap');
        end

        ts_LESO = out(i).LESODist;
        t_LESO = ts_LESO.Time;
        LESO_raw = squeeze(ts_LESO.Data);
        if size(LESO_raw,1) ~= length(t_LESO), LESO_raw = LESO_raw'; end
        for dim = 1:6
            LESODist_all(i,:,dim) = interp1(t_LESO, LESO_raw(:,dim), ...
                t_common, 'linear', 'extrap');
        end

        for dim = 1:3
            pos_all(i,:,dim) = interp1(t_raw, pos_raw(:,dim), ...
                t_common, 'linear', 'extrap');
            vel_all(i,:,dim) = interp1(t_raw, vel_raw(:,dim), ...
                t_common, 'linear', 'extrap');
        end

        for dim = 1:4
            quat_all(i,:,dim) = interp1(t_raw, quat_raw(:,dim), ...
                t_common, 'linear', 'extrap');
        end

        % Full-state target trajectory
        ts_target = out(i).target_pos_log;
        t_target = ts_target.Time;
        target_raw = squeeze(ts_target.Data);

        if size(target_raw, 1) ~= length(t_target)
            target_raw = target_raw';
        end

        % Allocate after observing the actual target-state width.
        if isempty(target_state_all)
            n_target_states = size(target_raw, 2);
            target_state_all = nan(num_sims, length(t_common), n_target_states);
        end

        if size(target_raw, 2) ~= size(target_state_all, 3)
            error(['Simulation %d: target trajectory state dimension changed ' ...
                   'from %d to %d.'], ...
                i, size(target_state_all,3), size(target_raw,2));
        end

        for dim = 1:size(target_raw,2)
            target_state_all(i,:,dim) = interp1( ...
                t_target, target_raw(:,dim), t_common, 'linear', 'extrap');
        end
    else
        warning('Simulation %d failed: %s', i, out(i).ErrorMessage);
        RMSE_Controls_all(:, i) = NaN;
        RMSE_Filter_all(:, i)   = NaN;
        RMSE_Wind_all(:, i)     = NaN;
    end
end

% Derived disturbance metrics for sensitivity analysis
disp('Calculating disturbance magnitudes...');

Lever_Radial = nan(num_sims,1);
Lever_Axial  = nan(num_sims,1);

J_Trans_Scale = nan(num_sims,1);
J_Axial_Scale = nan(num_sims,1);
J_Wobble_Coup = nan(num_sims,1);
J_Trans_Coup  = nan(num_sims,1);

Wind_Gain_all  = cell2mat(Wind_Gain_vals);
Wind_Covar_all = cell2mat(Wind_Covar_vals);

% V5 disturbance magnitudes
Wind_Mean_all      = cell2mat(Wind_Mean_vals);
Wind_Dir_all       = cell2mat(Wind_Dir_vals);
AccelBias_Mag      = cellfun(@norm, accelBias_vals);
GyroBias_Mag       = cellfun(@norm, gyroBias_vals);
HardIron_Mag       = cellfun(@norm, magHardIron_vals);
SoftIron_Dev       = cellfun(@(M) norm(M - magDist_nom, 'fro'), magDistMatrix_vals);
GimbalBias_Mag     = cellfun(@(g) norm(g(1:2)), gimbalBias_vals);
ThrustBias_all     = cellfun(@(g) g(3), gimbalBias_vals);

for i = 1:num_sims
    Lever_Radial(i) = norm(TB_d_vals{i}(1:2));
    Lever_Axial(i)  = abs(TB_d_vals{i}(3));

    dI_xx = J_d_vals{i}(1,1);
    dI_yy = J_d_vals{i}(2,2);
    dI_zz = J_d_vals{i}(3,3);
    dI_xy = J_d_vals{i}(1,2);
    dI_xz = J_d_vals{i}(1,3);
    dI_yz = J_d_vals{i}(2,3);

    J_Trans_Scale(i) = norm([dI_xx, dI_yy]);
    J_Axial_Scale(i) = abs(dI_zz);
    J_Wobble_Coup(i) = norm([dI_xz, dI_yz]);
    J_Trans_Coup(i)  = abs(dI_xy);
end

%%Target-relative trajectory metrics
% No waypoint assumptions are used. Compare each simulated trajectory to
% the full target trajectory directly. The state ordering used here follows
% the logged vehicle state convention from V3:
%   [q(1:4), position(1:3), velocity(1:3), ...]
if isempty(target_state_all) || size(target_state_all,3) < 7
    error(['The full-state target trajectory was not logged with the expected ' ...
           'position entries.']);
end

target_pos_all = target_state_all(:,:,5:7);
target_vel_all = target_state_all(:,:,8:10);

pos_error_all = pos_all - target_pos_all;
vel_error_all = vel_all - target_vel_all;

pos_error_rmse = squeeze(sqrt(mean(pos_error_all.^2, 2, 'omitnan')));
vel_error_rmse = squeeze(sqrt(mean(vel_error_all.^2, 2, 'omitnan')));

% Aggregate position / velocity errors for compact plotting.
Pos_RMSE_total = sqrt(sum(pos_error_rmse.^2, 2));
Vel_RMSE_total = sqrt(sum(vel_error_rmse.^2, 2));

%% V5 pass/fail per run
% Errors are measured against the target trajectory after the pad hold.
% A run that errored or produced no state counts as a failure.
eval_idx = t_common >= pad_hold_time;

pos_err_norm = sqrt(sum(pos_error_all.^2, 3));                 % num_sims x T
Pos_Err_Max  = max(pos_err_norm(:, eval_idx), [], 2);          % m

q_sim = quat_all ./ sqrt(sum(quat_all.^2, 3));
q_trg = target_state_all(:,:,1:4);
q_trg = q_trg ./ sqrt(sum(q_trg.^2, 3));
q_dot = abs(sum(q_sim .* q_trg, 3));
q_dot(q_dot > 1) = 1;                                          % keeps NaN as NaN
att_err_deg = 2 * acosd(q_dot);                                % num_sims x T
Att_Err_Max = max(att_err_deg(:, eval_idx), [], 2);            % deg

Fail_Error    = ~ok(:);
Fail_NoData   = isnan(Pos_Err_Max) | isnan(Att_Err_Max);
Fail_Position = Pos_Err_Max > pos_err_fail;
Fail_Attitude = Att_Err_Max > att_err_fail;
MC_Fail = Fail_Error | Fail_NoData | Fail_Position | Fail_Attitude;

fprintf('\nV5 pass/fail: %d of %d runs failed (%.1f%%)\n', ...
    nnz(MC_Fail), num_sims, 100 * nnz(MC_Fail) / num_sims);
fprintf('   sim error      %d\n', nnz(Fail_Error));
fprintf('   no state data  %d\n', nnz(Fail_NoData & ~Fail_Error));
fprintf('   position > %.1f m   %d\n', pos_err_fail, nnz(Fail_Position));
fprintf('   attitude > %.0f deg  %d\n', att_err_fail, nnz(Fail_Attitude));

disp('Data successfully calculated.');

% Auto-Save
save_data = 1;
if save_data
    disp('Saving workspace data...');
    save_dir = fullfile(pwd, 'Analysis', 'Monte Carlo Runs');
    if ~exist(save_dir, 'dir')
        mkdir(save_dir);
    end

    mat_filename = fullfile(save_dir, ...
        sprintf('MC5_%druns_%s.mat', num_sims, datestr(now, 'yyyymmdd_HHMM')));

    save(mat_filename, '-v7.3');
    disp(['Data saved successfully to: ', mat_filename]);
end

